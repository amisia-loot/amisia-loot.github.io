    bad.write_text(json.dumps({'spots': {'x': {'deDE': ['a'], 'enUS': []}}, 'q': {'1': {'spots': 'x'}}}), encoding='utf-8')
    with pytest.raises(SystemExit):
        bdq.load_hints(str(bad))
    assert bdq.load_hints('') == {}


