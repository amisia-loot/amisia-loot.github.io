def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='') as fh:
        fh.write(text)


def lua_load(text):
    assert 'ns.LazyData("QUEST_ITEMS", [' in text
    return lua_data.load(text, 'QuestItemData.lua').QUEST_ITEMS


@pytest.fixture
def wago(tmp_path):
    d = tmp_path / 'wago'
    d.mkdir()
    # 63101-63107 quest class; 63005 a key (13); 64001 starts quest 74001; 64002 a consumable that starts one
    write(str(d / 'Item.1.60.1.10.csv'), 'ID,ClassID,SubclassID\n' + ''.join(
        f'{i},12,0\n' for i in (63101, 63102, 63103, 63104, 63105, 63107, 64001)) + '63005,13,0\n64002,0,0\n63106,4,1\n')
    write(str(d / 'ItemSparse.1.60.1.10.csv'), 'ID,Display_lang,StartQuestID\n64001,Old Map,74001\n64002,Odd Brew,74002\n'
          '63101,Isle Writ,0\n')
    return str(d)


def test_the_client_tables(wago):
    classes, starts = bqi.read_client(wago)
    assert classes[63101] == 12 and classes[63005] == 13 and classes[63106] == 4
    assert starts == {64001: 74001, 64002: 74002}, 'a start quest 0 is none'
    assert bqi.read_client(None) == ({}, {})


def test_own_links_are_checked_as_the_addon_checks_them():
    db = {'questItems': {'v': 1, 'links': {63104: '73102', 63105: '73102,73999', 'x': '1', 63107: 'bad', 0: '5',
                                           63101: '73102,,7', 99999999: '5', 63103: '5,' + ','.join(['9'] * 20)}}}
    assert bqi.links_from_sv(db) == {63104: [73102], 63105: [73102, 73999], 63103: [5, 9]}
    assert bqi.links_from_sv({}) == {} and bqi.links_from_sv({'questItems': {'links': 'x'}}) == {}


def test_the_archive_keeps_every_link_once_seen(tmp_path):
    path = str(tmp_path / 'arch.json')
    got = bqi.update_archive([{'questItems': {'links': {63104: '73102'}}}], path, today='2026-11-10')
    assert got == {63104: [73102]}
    arch = json.load(open(path, encoding='utf-8'))
    assert arch == {'updated': '2026-11-10', 'links': {'63104': [73102]}}
    # a later file without the link and with a new one: both stay
    got = bqi.update_archive([{'questItems': {'links': {63105: '73102'}}}], path, today='2026-11-11')
    assert got == {63104: [73102], 63105: [73102]}
    before = open(path, encoding='utf-8').read()
    bqi.update_archive([{}], path, today='2026-11-12')
    assert open(path, encoding='utf-8').read() == before, 'nothing new: the file stays (the date too)'
    assert bqi.update_archive([{'questItems': {'links': {1: '2'}}}], None) == {1: [2]}, 'without an archive'


def test_the_links_with_their_kinds(wago):
    db = att_data.load(NEW, items=False)
    att = {q: r['items'] for q, r in db['quests'].items()}
    classes, starts = bqi.read_client(wago)
    data = bqi.build(att, starts, {63104: [73102, 74003], 64001: [74001]}, classes)
    assert data[63101] == {73102: 'D'} and data[63105] == {73102: 'D'} and data[63107] == {73103: 'D'}
    assert data[63104] == {73102: 'O', 74003: 'O'}, 'an own observation goes before the data'
    assert data[64001] == {74001: 'S'}, 'the client table goes before an own observation'
    assert 63005 not in data, 'a key, though the data links it'
    assert 64002 not in data, 'a consumable that starts a quest: the addon reads the bag item itself'
    assert 63106 not in data, 'a reward (armour) is no link anyway'
    # an item neither the client table nor the item export knows stays: the addon checks the class
    assert bqi.build({1: [55555]}, {}, {}, {}) == {55555: {1: 'D'}}
    assert bqi.build({1: [55555]}, {}, {}, {}, {55555: 2}) == {}, "the item export's class where the table lacks it"
    by = bqi.counts(data)
    assert by['S'] == 1 and by['O'] == 1 and by['D'] >= 5


def test_render_and_load(wago):
    data = {63104: {73102: 'O', 74003: 'D'}, 64001: {74001: 'S'}, 5: {q: 'D' for q in range(1, 20)}}
    text = bqi.render(data, '2026-11-10', 'test')
    assert text == bqi.render(data, '2026-11-10', 'test'), 'the same text twice'
    assert text.startswith('-- GENERATED by tools/build_questitems.py')
    qi = lua_load(text)
    assert qi.built == '2026-11-10' and qi.count == 3
    assert qi.I[63104] == 'O73102,D74003' and qi.I[64001] == 'S74001'
    assert qi.I[5] == ','.join(f'D{q}' for q in range(1, bqi.MAX_QUESTS + 1)), 'at most eight quests per item'
    empty = lua_load(bqi.render({}, 'x', 'none yet'))
    assert empty.count == 0


def test_main_writes_the_file(tmp_path, wago):
    out, arch = str(tmp_path / 'QuestItemData.lua'), str(tmp_path / 'arch.json')
    sv = tmp_path / 'Amisia.lua'
    sv.write_text('AmisiaDB = { ["questItems"] = { ["v"] = 1, ["links"] = { [63104] = "74003" } } }\n', encoding='utf-8')
    bqi.main(['--att', NEW, '--wago', wago, '--sv', str(sv), '--archive', arch, '--out', out])
    qi = lua_load(open(out, encoding='utf-8').read())
    assert qi.I[63104] == 'D73102,O74003' and qi.I[64001] == 'S74001'
    assert json.load(open(arch, encoding='utf-8'))['links'] == {'63104': [74003]}
    head = open(out, encoding='utf-8').read().split('\n')[1]
    assert 'MIT' in head and 'client tables' in head and 'own observations' in head
    bqi.main(['--empty', '--out', out])
    assert lua_load(open(out, encoding='utf-8').read()).count == 0


def test_the_shipped_file():
    path = os.path.join(ADDON, 'Data', 'QuestItemData.lua')
    with open(path, encoding='utf-8') as fh:
        text = fh.read()
    assert text.startswith('-- GENERATED by tools/build_questitems.py')
    assert os.path.getsize(path) < 120 * 1024, 'one short string per item'
    qi = lua_load(text)
    assert qi.count == len(list(qi.I.keys()))
    for v in list(qi.I.values())[:200]:
        assert re.fullmatch(r'[SOD]\d+(,[SOD]\d+)*', v), v
    for toc in ('Amisia_Gear.toc',):
        with open(os.path.join(ADDON, toc), encoding='utf-8') as fh:
            t = fh.read()
        assert re.search(r'^Data\\QuestItemData\.lua$', t, re.M)
        assert t.index('Data\\QuestData.lua') < t.index('Data\\QuestItemData.lua') < t.index('Gear\\QuestItems.lua')
    with open(os.path.join(ROOT, 'Amisia', 'LICENSES', 'AllTheThings-MIT.txt'), encoding='utf-8') as fh:
        assert 'QuestItemData.lua' in fh.read().split('used under this licence')[0]
