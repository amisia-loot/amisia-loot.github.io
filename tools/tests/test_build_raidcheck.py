"""tools/build_raidcheck.py: the raid check's lists (flasks, elixirs, food, class buffs, enchanted
slots) from the client tables (hand-made fixture CSVs in tests/fixtures/wago_raidcheck, not real
data), the fallback without SpellEquippedItems, and the generated Amisia/Data/RaidCheckData.lua
(valid Lua, lazy, in the TOC before the raid check)."""
import os
import re
import shutil
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
ROOT = os.path.dirname(TOOLS)
ADDON = os.path.join(ROOT, 'Amisia')
sys.path.insert(0, TOOLS)
import build_raidcheck  # noqa: E402
import lua_data  # noqa: E402

FIX = os.path.join(HERE, 'fixtures', 'wago_raidcheck')
OUT = os.path.join(ADDON, 'Data', 'RaidCheckData.lua')


@pytest.fixture(scope='module')
def data():
    return build_raidcheck.build([FIX])


def test_flasks_are_the_use_spells_of_flask_items(data):
    assert data['build'] == '1.60.1.99999'
    assert data['flask'] == {5000: 100, 5001: 101}


def test_elixirs_only_long_auras(data):
    # "Cure Poison" applies no aura, the short elixir lasts 2 minutes
    assert data['elixir'] == {5100: 200}


def test_food_follows_the_trigger_to_well_fed(data):
    # the use spell triggers the eating aura (21 s, out) and the buff (15 min); a drink without a
    # buff is out; a "Well Fed" spell no item names is in with item 0
    assert data['food'] == {5210: 300, 5211: 302, 5300: 0}
    assert 434 not in data['food'] and 5200 not in data['food'] and 5201 not in data['food']


def test_class_buffs_every_rank_by_name(data):
    by = {b['key']: b for b in data['buffs']}
    assert [b['key'] for b in data['buffs']] == ['int', 'sta', 'wild', 'spirit', 'bless']
    assert by['int']['class'] == 'MAGE' and by['int']['spells'] == [6001, 6002, 6003], 'not a spell of a longer name'
    assert by['sta']['class'] == 'PRIEST' and by['sta']['spells'] == [6010]
    assert by['spirit']['talent'] is True and by['int']['talent'] is False
    assert by['bless']['class'] == 'PALADIN' and by['bless']['spells'] == [6040, 6041]


def test_without_spell_equipped_items_the_fixed_list(data):
    assert data['slotsFrom'] == 'list' and data['slots'] == [15, 5, 9, 10, 8, 16, 17]


def test_with_spell_equipped_items_the_recipes_slots(tmp_path):
    for name in os.listdir(FIX):
        shutil.copy(os.path.join(FIX, name), tmp_path / name)
    (tmp_path / 'SkillLineAbility.1.60.1.99999.csv').write_text(
        'ID,SkillLine,Spell\n1,333,7000\n2,333,7001\n3,333,7002\n4,333,7003\n5,164,7004\n', encoding='utf-8')
    # 7000 cloak (InventoryType 16), 7001 chest and robe (5, 20), 7002 a weapon, 7003 the head (never),
    # 7004 blacksmithing (not an enchanter's)
    (tmp_path / 'SpellEquippedItems.1.60.1.99999.csv').write_text(
        'ID,SpellID,EquippedItemClass,EquippedItemInvTypes,EquippedItemSubclass\n'
        f'1,7000,4,{1 << 16},0\n2,7001,4,{(1 << 5) | (1 << 20)},0\n3,7002,2,0,0\n4,7003,4,{1 << 1},0\n5,7004,4,{1 << 10},0\n',
        encoding='utf-8')
    d = build_raidcheck.build([str(tmp_path)])
    assert d['slotsFrom'] == 'table' and d['slots'] == [15, 5, 16]


def test_lua_output_lazy_and_valid(data):
    lua = build_raidcheck.render_lua(data, built='2026-10-12')
    assert lua.startswith('-- Generated by tools/build_raidcheck.py from the WoW Forever client tables')
    assert 'ns.LazyData("RAIDCHECK", [=[\nreturn {\n' in lua and lua.rstrip().endswith(']=], 6)')
    lupa = pytest.importorskip('lupa.lua51')
    t = lua_data.load(lua, 'RaidCheckData.lua', lupa.LuaRuntime(unpack_returned_tuples=True)).RAIDCHECK
    assert t.flask[5000] == 100 and t.elixir[5100] == 200 and t.food[5300] == 0 and t.shield == 17
    assert t.buffs[1][1] == 'int' and t.buffs[1][2] == 'MAGE' and t.buffs[4][3] == 1 and t.buffs[1][4][3] == 6003
    assert t.slots[1] == 15 and t.slotsFrom == 'list'


def test_missing_table_fails_clearly(tmp_path):
    with pytest.raises(SystemExit) as e:
        build_raidcheck.build([str(tmp_path)])
    assert 'Item' in str(e.value)


def test_empty_file_loads():
    lupa = pytest.importorskip('lupa.lua51')
    lua = build_raidcheck.render_lua(build_raidcheck.empty_data(), built='x')
    t = lua_data.load(lua, 'RaidCheckData.lua', lupa.LuaRuntime(unpack_returned_tuples=True)).RAIDCHECK
    assert len(list(t.flask.keys())) == 0 and t.slots[1] == 15


def test_export_script_asks_for_spell_equipped_items():
    with open(os.path.join(TOOLS, 'export_db2.ps1'), encoding='utf-8') as fh:
        text = fh.read()
    assert "'SpellEquippedItems'" in text


def test_shipped_data_file_in_toc_and_valid():
    with open(os.path.join(ADDON, 'Amisia.toc'), encoding='utf-8') as fh:
        toc = fh.read()
    assert 'Data\\RaidCheckData.lua [AllowLoadGameType camelot]' in toc
    assert toc.index('Data\\RaidCheckData.lua') < toc.index('Raid\\RaidCheck.lua')
    with open(OUT, encoding='utf-8') as fh:
        src = fh.read()
    lupa = pytest.importorskip('lupa.lua51')
    t = lua_data.load(src, 'RaidCheckData.lua', lupa.LuaRuntime(unpack_returned_tuples=True)).RAIDCHECK
    n = int(src.rsplit(', ', 1)[1].rstrip(')\n'))
    count = sum(len(list(t[k].keys())) for k in ('flask', 'elixir', 'food'))
    assert n == count, 'the count is the number of flask, elixir and food spells'
    assert len(list(t.buffs.keys())) == 5


@pytest.mark.skipif(not os.path.isdir(build_raidcheck.WAGO), reason='needs the client tables')
def test_shipped_file_is_current():
    dirs = [build_raidcheck.WAGO]
    if any(build_raidcheck.find_table(dirs, t) is None for t in build_raidcheck.REQUIRED):
        pytest.skip('no client tables')
    with open(OUT, encoding='utf-8') as fh:
        shipped = fh.read()
    built = re.search(r'built\s*=\s*"([^"]*)"', shipped).group(1)
    assert build_raidcheck.render_lua(build_raidcheck.build(dirs), built=built) == shipped, \
        'rebuild: python3 tools/build_raidcheck.py'
