"""tools/build_site_drops.py (F-187, D-119): the guild's boss kills from the SavedVariables into the archive
tools/drop_obs.json and the site's data/drops-forever.js, so the Loot Tables tab shows them without
pasting. The file holds what the text "Drops für die Website" holds, without exporter, origin or any
other name than the bosses' and the instances'; it is stable (the same archive gives the same bytes),
the archive keeps kills the addon's 28 days dropped, and BUILD_ID rises only when the file changes.
All with made-up data; the committed file is checked against the committed archive only.
"""
import json
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import build_scan  # noqa: E402
import build_site_drops as bsd  # noqa: E402

INDEX = "<script>\nconst PLAY = 'forever';\nconst BUILD_ID = '1790000000';\n</script>\n"


def sv_text(kills, me='3fa9c2e1'):
    """An Amisia.lua with the drop records `kills` {id: (npc, inst, day, origin, src, {item: n}, mine)}."""
    rows = []
    for h, (npc, inst, day, o, src, it, mine) in kills.items():
        items = ', '.join(f'[{i}] = {n}' for i, n in it.items())
        enc = ', enc = 3020' if src == 'E' else ''
        rows.append(f'["{h}"] = {{ npc = {npc}, inst = {inst}, diff = 1, day = {day}, o = "{o}", src = "{src}"{enc}, '
                    f'it = {{ {items} }}{", mine = true" if mine else ""} }},')
    return ('AmisiaDB = {\n  drops = {\n    v = 1, me = "' + me + '",\n    k = {\n      ' + '\n      '.join(rows) + '\n    },\n'
            '    npc = { [213450] = "Faldrim Ambossmahl", [213470] = "Kurgor der Wächter", [999999] = "Ohne Kill" },\n'
            '    inst = { [2834] = { "party", "Halle der Thane" }, [409] = { "raid", "Geschmolzener Kern" } },\n'
            '    enc = { [3020] = "Geheimer Boss" },\n'
            '    peers = { ["77777777"] = 300 },\n  },\n'
            '  char = { name = "Vulo", realm = "Sturmwind", guild = "Amisia" },\n}\n')


KILLS = {
    'a0000002': (213450, 2834, 301, '3fa9c2e1', 'G', {219006: 2, 219004: 1}, True),
    'a0000001': (213450, 2834, 300, '11111111', 'G', {}, False),
    'a0000003': (213470, 409, 301, '22222222', 'G', {219005: 1}, False),
    'a0000004': (0, 2834, 300, '3fa9c2e1', 'E', {219009: 1}, True),
}


@pytest.fixture
def place(tmp_path):
    index = tmp_path / 'index.html'
    index.write_text(INDEX, encoding='utf-8')
    return {'archive': str(tmp_path / 'drop_obs.json'), 'out': str(tmp_path / 'drops-forever.js'), 'index': str(index),
            'sv': str(tmp_path / 'Amisia.lua'), 'tmp': tmp_path}


def run(place, svs, now=1795000000):
    lines = []
    res = bsd.build(svs, place['archive'], place['out'], place['index'], now=now, log=lines.append)
    return res, lines


def data_of(path):
    with open(path, encoding='utf-8') as fh:
        text = fh.read()
    body = text.split(bsd.PREFIX, 1)[1]
    return text, json.loads(body.rstrip().rstrip(';'))


def build_id(place):
    with open(place['index'], encoding='utf-8') as fh:
        return bsd.BUILD_ID_RE.search(fh.read()).group(1)


def test_the_file_holds_the_kills_of_the_text_without_names_of_players_or_clients(place):
    with open(place['sv'], 'w', encoding='utf-8') as fh:
        fh.write(sv_text(KILLS))
    res, _ = run(place, [place['sv']])
    assert res['kills'] == 4 and res['file'] and res['archive']
    text, d = data_of(place['out'])
    assert text.startswith('// GENERATED by tools/build_site_drops.py from tools/drop_obs.json')
    assert d['v'] == 1
    # sorted by day, then id; [id, npc, instance, difficulty, day, G|E, [item, count, ...]] with items by id
    assert d['k'] == [['a0000001', 213450, 2834, 1, 300, 'G', []],
                      ['a0000004', 0, 2834, 1, 300, 'E', [219009, 1]],
                      ['a0000002', 213450, 2834, 1, 301, 'G', [219004, 1, 219006, 2]],
                      ['a0000003', 213470, 409, 1, 301, 'G', [219005, 1]]]
    # the names the kills use, nothing else (a boss without a kill stays out)
    assert d['names'] == {'213450': 'Faldrim Ambossmahl', '213470': 'Kurgor der Wächter'}
    assert d['zones'] == {'409': ['raid', 'Geschmolzener Kern'], '2834': ['party', 'Halle der Thane']}
    for word in ('3fa9c2e1', '11111111', '22222222', '77777777', 'Vulo', 'Sturmwind', 'Amisia"', 'mine', 'Geheimer Boss'):
        assert word not in text, f'{word} must not be in the public file'


def test_the_same_archive_gives_the_same_bytes_and_build_id_stays(place):
    with open(place['sv'], 'w', encoding='utf-8') as fh:
        fh.write(sv_text(KILLS))
    first, _ = run(place, [place['sv']], now=1795000000)
    assert first['build_id'] == '1795000000' and build_id(place) == '1795000000'
    with open(place['out'], 'rb') as fh:
        before = fh.read()
    again, lines = run(place, [place['sv']], now=1795000500)
    assert again == {'kills': 4, 'archive': False, 'file': False, 'build_id': None}
    with open(place['out'], 'rb') as fh:
        assert fh.read() == before
    assert build_id(place) == '1795000000', 'an unchanged file keeps BUILD_ID'
    assert any('(unchanged)' in line for line in lines)


def test_the_archive_keeps_kills_the_addon_dropped_and_merges_one_kill_once(place):
    with open(place['sv'], 'w', encoding='utf-8') as fh:
        fh.write(sv_text(KILLS))
    run(place, [place['sv']])
    # 28 days later the addon holds only a0000003 (seen again with one more item) and a new kill
    later = {'a0000003': (213470, 409, 301, '00000001', 'G', {219005: 1, 219010: 1}, False),
             'a0000005': (213470, 409, 315, '3fa9c2e1', 'G', {219005: 1}, True)}
    with open(place['sv'], 'w', encoding='utf-8') as fh:
        fh.write(sv_text(later))
    res, _ = run(place, [place['sv']], now=1795000100)
    assert res['kills'] == 5 and res['build_id'] == '1795000100'
    _, d = data_of(place['out'])
    by = {k[0]: k for k in d['k']}
    assert sorted(by) == ['a0000001', 'a0000002', 'a0000003', 'a0000004', 'a0000005']
    assert by['a0000003'][6] == [219005, 1, 219010, 1], 'the same kill twice is one, its items joined'
    assert build_scan.load_archive(place['archive'])['k']['a0000003']['o'] == '00000001', 'the archive keeps the origin, the file does not'


def test_without_savedvariables_the_file_is_written_empty_and_nothing_else_changes(place):
    res, lines = run(place, [])
    assert res['kills'] == 0 and res['file'] and res['build_id'] == '1795000000'
    _, d = data_of(place['out'])
    assert d == {'v': 1, 'k': [], 'names': {}, 'zones': {}}
    assert any('no SavedVariables' in line for line in lines)
    again, _ = run(place, [])
    assert again['file'] is False and again['build_id'] is None


def test_a_broken_savedvariables_file_does_not_stop_the_build(place):
    with open(place['sv'], 'w', encoding='utf-8') as fh:
        fh.write('AmisiaDB = {')
    res, lines = run(place, [place['sv']])
    assert res['kills'] == 0 and any('not read' in line for line in lines)


def test_build_id_rises_to_now_and_at_least_by_one(tmp_path):
    p = tmp_path / 'index.html'
    p.write_text(INDEX, encoding='utf-8')
    assert bsd.bump_build_id(str(p), now=1795000000) == '1795000000'
    assert bsd.bump_build_id(str(p), now=1700000000) == '1795000001', 'a clock behind the old value still raises it'
    assert p.read_text(encoding='utf-8') == INDEX.replace('1790000000', '1795000001'), 'only the number changes'
    (tmp_path / 'bad.html').write_text('<script></script>', encoding='utf-8')
    with pytest.raises(SystemExit):
        bsd.bump_build_id(str(tmp_path / 'bad.html'))


def test_the_committed_file_is_the_committed_archive():
    """Whoever commits a changed tools/drop_obs.json commits the file built from it (build.py data does both)."""
    with open(bsd.OUT, encoding='utf-8') as fh:
        assert fh.read() == bsd.render(build_scan.load_archive(bsd.ARCHIVE)), \
            'Amisia-Website/data/drops-forever.js is not current: python3 tools/build_site_drops.py --sv'
