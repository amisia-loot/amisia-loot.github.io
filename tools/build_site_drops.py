"""Builds Amisia-Website/data/drops-forever.js: the guild's boss kills for the site's Loot Tables tab (F-187, D-119).

    python3 tools/build_site_drops.py [--sv FILE ...] [--archive FILE] [--out FILE] [--index FILE]

The addon records every boss kill whose loot window a guild member opens and shares the records in the
guild (Amisia/Collect/Drops.lua, DropSync.lua); the SavedVariables hold them for 28 days. This step joins
the records of the SavedVariables (`drops.k`, own and heard; default ~/addons/_SavedVariables/Amisia.lua,
which Syncthing brings to the N100) into the archive tools/drop_obs.json, where they stay for good (the
same archive and merge rules as tools/build_scan.py: one kill per id, each item at its larger count, the
earlier day), and writes every kill of the archive as a static data file of the site, so the kills reach
the Loot Tables tab with each data build and nobody has to paste the text "Drops für die Website".

The file holds what that text holds, without the parts that name a player or a client:
  k      the kills, sorted by day, then id: [id, npc, instance, difficulty, day, G|E, [item, count, ...]]
         (id = the addon's kill id, a hash of the corpse GUID; day = days since 2026-01-01 UTC; items by id)
  names  boss names by NPC id, zones [party|raid, name] by instance id: only those the kills use
No exporter name (the text's head line), no origin (the random client id of each record), no guild,
realm or account. The site counts a kill once by its id, whether it comes from this file, from the ledger
or from both (index.html dropTables).

The output depends on the archive only, so an unchanged archive gives the same bytes; with no kills
the file is still written (an empty list). When the file's content changes, BUILD_ID in
Amisia-Website/index.html is raised (to the current Unix time, at least one more than before), so
browsers fetch the new file. Nothing here asks the network or writes to Supabase.
"""
import argparse
import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import build_scan  # noqa: E402

GAME = 'forever'
OUT = os.path.join(ROOT, 'Amisia-Website', 'data', 'drops-' + GAME + '.js')
INDEX = os.path.join(ROOT, 'Amisia-Website', 'index.html')
ARCHIVE = build_scan.DROP_ARCHIVE
DEFAULT_SV = build_scan.DEFAULT_SV
HEAD = ('// GENERATED by tools/build_site_drops.py from tools/drop_obs.json (the guild\'s drop records from the\n'
        '// addon\'s SavedVariables; F-187, D-119). No player, guild, realm or client names. Do not edit.\n')
PREFIX = 'window.__DROPS=window.__DROPS||{};window.__DROPS["' + GAME + '"]='
BUILD_ID_RE = re.compile(r"const BUILD_ID = '(\d+)';")


def site_data(arch):
    """The file's data from the archive: kills sorted by day, then id, and the names they use."""
    kills, npcs, insts = [], set(), set()
    for h in sorted(arch['k'], key=lambda h: (arch['k'][h]['day'], h)):
        r = arch['k'][h]
        items = []
        for i in sorted(r['it']):
            items += [i, r['it'][i]]
        kills.append([h, r['npc'], r['inst'], r['diff'], r['day'], r['src'], items])
        if r['npc'] > 0:
            npcs.add(r['npc'])
        insts.add(r['inst'])
    names = {str(n): arch['npc'][n] for n in sorted(npcs) if n in arch['npc']}
    zones = {str(i): list(arch['inst'][i]) for i in sorted(insts) if i in arch['inst']}
    return {'v': 1, 'k': kills, 'names': names, 'zones': zones}


def render(arch):
    return HEAD + PREFIX + json.dumps(site_data(arch), ensure_ascii=False, separators=(',', ':')) + ';\n'


def bump_build_id(index_path, now=None):
    """Raises BUILD_ID in index.html to the current Unix time, at least one above the old value. The new value."""
    with open(index_path, encoding='utf-8') as fh:
        text = fh.read()
    m = BUILD_ID_RE.search(text)
    if not m:
        raise SystemExit(f'{index_path}: no line "const BUILD_ID = \'<digits>\';"')
    new = str(max(int(m.group(1)) + 1, int(time.time() if now is None else now)))
    text = text[:m.start(1)] + new + text[m.end(1):]
    with open(index_path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    return new


def archive_text(arch):
    return json.dumps({'k': arch['k'], 'npc': arch['npc'], 'inst': arch['inst'], 'enc': arch['enc']},
                      sort_keys=True, default=str)


def build(svs=None, archive=ARCHIVE, out=OUT, index=INDEX, now=None, log=print):
    """Joins the SavedVariables into the archive and writes the site file. svs None: the default file when
    it is there. Returns {'kills', 'archive' (changed), 'file' (changed), 'build_id' (new or None)}."""
    arch = build_scan.load_archive(archive)
    before = archive_text(arch)
    dbs = []
    for p in ([DEFAULT_SV] if svs is None and os.path.exists(DEFAULT_SV) else (svs or [])):
        try:
            dbs.append(build_scan.load_sv(p))
        except (SystemExit, Exception) as exc:  # noqa: BLE001 - a broken file must not stop the data build
            log(f'  {p}: not read ({exc})')
    if dbs:
        build_scan.gather_drops(arch, dbs, [], [], log=lambda line: log('  ' + line))
    else:
        log('  no SavedVariables: the archive as it is')
    arch_changed = archive_text(arch) != before or not os.path.exists(archive)
    if arch_changed:
        build_scan.save_archive(archive, arch)
    text = render(arch)
    old = None
    if os.path.exists(out):
        with open(out, encoding='utf-8') as fh:
            old = fh.read()
    new_id = None
    if text != old:
        with open(out, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
        new_id = bump_build_id(index, now) if index else None
    rel = lambda p: os.path.relpath(p, ROOT)  # noqa: E731
    log(f'site drops: {len(arch["k"])} kills -> {rel(out)}' + (' (unchanged)' if text == old else '')
        + (f'; BUILD_ID {new_id}' if new_id else '') + (f'; {rel(archive)} updated' if arch_changed else ''))
    return {'kills': len(arch['k']), 'archive': arch_changed, 'file': text != old, 'build_id': new_id}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--sv', nargs='*', help='Amisia SavedVariables files (default: ~/addons/_SavedVariables/Amisia.lua when it is there)')
    ap.add_argument('--archive', default=ARCHIVE, help='the archive of drop records (default tools/drop_obs.json)')
    ap.add_argument('--out', default=OUT, help='the site file (default Amisia-Website/data/drops-forever.js)')
    ap.add_argument('--index', default=INDEX, help='the page whose BUILD_ID is raised when the file changes')
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    build(args.sv, args.archive, args.out, args.index)
    return 0


if __name__ == '__main__':
    sys.exit(main())
